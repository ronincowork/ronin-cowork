// The Tools help page's list, generated from ronin_stock/tools/*.md headers.
// `node scripts/tool-list.mjs` rewrites it; `--check` exits 1 when the page is stale.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'ronin_stock', 'tools');
const page = path.join(root, 'docs', 'using-ronin', 'agent-tools.md');
const START = '<!-- tool-list: generated by scripts/tool-list.mjs from ronin_stock/tools; do not edit -->';
const END = '<!-- /tool-list -->';

export function header(text) {
  const lines = text.split('\n');
  const out = { title: lines[0].replace(/^#\s*/, '').trim() };
  for (const line of lines.slice(1)) {
    if (!line.trim()) break;
    const m = /^- \*\*([\w ]+):\*\*\s*(.*)$/.exec(line);
    if (m) out[m[1].trim()] = m[2].trim();
  }
  return out;
}

export function list() {
  return readdirSync(dir).filter((f) => f.endsWith('.md') && !/readme\.md$/i.test(f))
    .map((f) => header(readFileSync(path.join(dir, f), 'utf8')))
    .filter((h) => h.depth !== 'none' && h.seed)
    .sort((a, b) => (Number(a.order) || 0) - (Number(b.order) || 0) || a.title.localeCompare(b.title))
    .map((h) => `- \`${h.title.replace(/`/g, '')}\`: ${h.seed}`)
    .join('\n');
}

const text = readFileSync(page, 'utf8');
const a = text.indexOf(START), b = text.indexOf(END);
if (a < 0 || b < a) { console.error(`${page}: no ${START} … ${END} block`); process.exit(2); }
const next = `${text.slice(0, a)}${START}\n${list()}\n${text.slice(b)}`;
if (process.argv.includes('--check')) {
  if (next !== text) { console.error('docs/using-ronin/agent-tools.md is stale: run node scripts/tool-list.mjs'); process.exit(1); }
} else if (next !== text) writeFileSync(page, next);
