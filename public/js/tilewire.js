/* part of the ronin-cowork client — see js/README.md */

/** How long a parcel waits for the host's answer before the composer is told it is unconfirmed. */
export const PARCEL_TIMEOUT_MS = 8000;

export class TileWire {
  /**
   * @param {{onStatus: (state: string) => void, onControl: (msg: object) => void,
   *          onBytes: (bytes: Uint8Array) => void, onDrop: () => void,
   *          reopen: (session: string) => void}} hooks
   */
  constructor(hooks) {
    this.hooks = hooks;
    this.ws = null;
    this.retry = null;
    this.wantOpen = false;
    this.session = null;
    this.parcels = new Map(); // id → settle(outcome), one per composer message in flight
    this.parcelSeq = 0;
  }

  connected() {
    return !!this.ws && this.ws.readyState === 1;
  }

  /** Housekeeping messages. Quiet: returns whether it went, tells nobody if it didn't. */
  send(msg) {
    if (!this.connected()) return false;
    this.ws.send(JSON.stringify(msg));
    return true;
  }

  /**
   * A keystroke, a parcel, an injected wheel escape — anything a person caused.
   * Reports the drop so the tile can show it.
   */
  sendInput(d) {
    if (this.send({ t: 'i', d })) return true;
    this.hooks.onDrop();
    return false;
  }

  /** A reply generated by xterm for its PTY peer, never person input or a DVR parcel. */
  sendTerminalReply(d) {
    return this.send({ t: 'p', d });
  }

  /**
   * A composer message — the whole text with its Enter — sent as its own frame and
   * answered by the host by id. Resolves to the truth the composer acts on: `{ok: true}`
   * once the bytes reached the terminal, otherwise `{ok: false, why}`. Never rejects.
   */
  sendParcel(d, timeoutMs = PARCEL_TIMEOUT_MS) {
    if (!this.connected()) {
      this.hooks.onDrop();
      return Promise.resolve({ ok: false, why: 'not connected' });
    }
    const id = String(++this.parcelSeq);
    return new Promise((resolve) => {
      const settle = (outcome) => {
        clearTimeout(timer);
        this.parcels.delete(id);
        resolve(outcome);
      };
      const timer = setTimeout(() => settle({ ok: false, why: 'unconfirmed' }), timeoutMs);
      this.parcels.set(id, settle);
      this.ws.send(JSON.stringify({ t: 'm', id, d }));
    });
  }

  /** The socket went away under parcels still waiting: each is told, none is retried. */
  settleParcels(why) {
    for (const settle of [...this.parcels.values()]) settle({ ok: false, why });
  }

  clearRetry() {
    if (!this.retry) return;
    clearTimeout(this.retry);
    this.retry = null;
  }

  /** Drop the socket without giving up the tile's intent to be connected. */
  drop() {
    if (!this.ws) return;
    try {
      this.ws.close();
    } catch (_) {}
    this.ws = null;
    this.settleParcels('disconnected');
  }

  /** Stop wanting a connection at all. */
  close() {
    this.wantOpen = false;
    this.session = null;
    this.clearRetry();
    this.drop();
  }

  /**
   * Open the socket for one session.
   *
   * Locked rides the attach mirror (the original pipeline, untouched). Unlocked rides
   * the recorded stream: seed = recent history, then the live pane output.
   */
  open({ session, locked, output, cols, rows, tapeAt }) {
    this.wantOpen = true;
    this.session = session;
    this.clearRetry();
    this.drop();

    const proto = location.protocol === 'https:' ? 'wss' : 'ws';
    const url =
      `${proto}://${location.host}/pty?session=${encodeURIComponent(session)}` +
      `&cols=${cols}&rows=${rows}` +
      (locked ? '' : '&mode=stream&view=' + encodeURIComponent(output || 'terminal_mirror') + (tapeAt ? `&seg=${tapeAt.seg}&off=${tapeAt.off}` : ''));
    const ws = new WebSocket(url);
    ws.binaryType = 'arraybuffer';
    this.ws = ws;

    ws.onopen = () => {
      this.hooks.onStatus('on');
      this.hooks.onOpen();
    };
    ws.onmessage = (ev) => {
      if (typeof ev.data === 'string') {
        let m;
        try {
          m = JSON.parse(ev.data);
        } catch (_) {
          return;
        }
        if (m.t === 'm' && this.parcels.has(m.id)) {
          this.parcels.get(m.id)(m.ok ? { ok: true } : { ok: false, why: m.why || 'refused' });
          return;
        }
        this.hooks.onControl(m);
        return;
      }
      this.hooks.onBytes(new Uint8Array(ev.data));
    };
    ws.onclose = () => {
      if (this.ws !== ws) return;
      this.settleParcels('disconnected');
      this.hooks.onStatus('off');
      if (this.wantOpen && this.session === session) {
        this.retry = setTimeout(() => {
          if (this.wantOpen && this.session === session) this.hooks.reopen(session);
        }, 2000);
      }
    };
    ws.onerror = () => this.hooks.onStatus('off');
  }
}
